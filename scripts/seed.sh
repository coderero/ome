#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

DATA="${OME_DATA:-data}"
BOTS_FILE="$DATA/bots.conf"
admin() { ./target/release/ome --user admin --secret "${OME_ADMIN_SECRET:-admin}" "$@"; }

mkdir -p "$DATA"
echo "# strategy:SYMBOL:username:secret, generated by scripts/seed.sh" >"$BOTS_FILE"

admin create-account alice alice-pw retail 25000
admin create-account bob bob-pw retail 10000
admin create-account fund fund-pw institutional 5000000

listings=(
  "ACME 25.00 20000 Acme Robotics"
  "NOVA 12.50 40000 Nova Energy"
  "ZEN 80.00 6000 Zen Biotech"
)

for listing in "${listings[@]}"; do
  read -r symbol price shares name <<<"$listing"
  lower="${symbol,,}"
  issuer="${lower}_ir"

  admin create-account "$issuer" "$issuer-pw" institutional 0
  admin ipo "$symbol" "$price" "$shares" "$issuer" "$name"

  for n in 1 2; do
    bot="${lower}_mm$n"
    admin create-account "$bot" bot-pw bot 250000
    admin set-shares "$bot" "$symbol" $(( shares / 10 ))
    echo "mm:$symbol:$bot:bot-pw" >>"$BOTS_FILE"
  done
  for strategy in momentum meanrev; do
    bot="${lower}_$strategy"
    admin create-account "$bot" bot-pw bot 150000
    echo "$strategy:$symbol:$bot:bot-pw" >>"$BOTS_FILE"
  done
  for n in 1 2 3; do
    bot="${lower}_noise$n"
    admin create-account "$bot" bot-pw bot 40000
    admin set-shares "$bot" "$symbol" $(( shares / 100 ))
    echo "noise:$symbol:$bot:bot-pw" >>"$BOTS_FILE"
  done
done

echo "seeded $(grep -vc '^#' "$BOTS_FILE") bots into $BOTS_FILE"
