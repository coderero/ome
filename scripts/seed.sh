#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
source scripts/env.sh

seed_members() {
  exchange_cmd add-member ccp "$OME_MEMBER_SECRET" clearing
  for p in "${providers[@]}" "${venues[@]}"; do
    read -r name _ member _ <<<"$p"
    exchange_cmd add-member "$name" "$OME_MEMBER_SECRET" "$member"
  done
}

seed_venues() {
  wait_for venue_cmd wholesale-co register retail-co "$OME_MEMBER_SECRET" || true
  wait_for venue_cmd ats-co register prime-co "$OME_MEMBER_SECRET" || true
}

registered() { clearing_cmd status | grep -q " $1 "; }

seed_clearing() {
  for p in "${providers[@]}" "wholesale-co"; do
    read -r name _ _ _ <<<"$p"
    wait_for clearing_cmd register "$name" "$OME_MEMBER_SECRET" || registered "$name"
    clearing_cmd deposit "$name" "$OME_COLLATERAL"
  done
}

account_id() { awk '{print $2}'; }

listed_everywhere() {
  local symbol="$1" name
  for p in "${providers[@]}"; do
    read -r name _ _ _ <<<"$p"
    broker_admin "$name" instruments | grep -q "^$symbol " || return 1
  done
}

subscribe_ipo() {
  local provider="$1" user="$2" symbol="$3" price="$4" qty="$5"
  broker_as "$provider" "$user" bot-pw buy "$symbol" "$price" "$qty" | tail -1
}

seed_market() {
  local bots="$OME_DATA/bots.conf"
  echo "# strategy:SYMBOL:username:secret@broker, generated by scripts/seed.sh" >"$bots"

  broker_admin retail-co create-account alice alice-pw retail 25000
  broker_admin retail-co create-account bob bob-pw retail 10000
  broker_admin prime-co create-account fund fund-pw quant 5000000

  local listings=(
    "ACME 25.00 20000 Acme Robotics"
    "NOVA 12.50 40000 Nova Energy"
    "ZEN 80.00 6000 Zen Biotech"
  )
  for listing in "${listings[@]}"; do
    read -r symbol price shares name <<<"$listing"
    local lower="${symbol,,}"

    local issuer
    issuer="$(broker_admin prime-co create-account "${lower}_ir" "${lower}-ir-pw" issuer 0 | account_id)"
    exchange_cmd ipo "$symbol" "$price" "$shares" prime-co "$issuer" "$name"
    wait_for listed_everywhere "$symbol"

    for n in 1 2; do
      broker_admin lp-co create-account "${lower}_mm$n" bot-pw lp 250000
      subscribe_ipo lp-co "${lower}_mm$n" "$symbol" "$price" $(( shares / 10 ))
      echo "mm:$symbol:${lower}_mm$n:bot-pw@$(provider_addr lp-co)" >>"$bots"
    done
    broker_admin dma-co create-account "${lower}_hft" bot-pw hft 400000
    subscribe_ipo dma-co "${lower}_hft" "$symbol" "$price" $(( shares / 20 ))
    echo "mm:$symbol:${lower}_hft:bot-pw@$(provider_addr dma-co)" >>"$bots"

    broker_admin prime-co create-account "${lower}_momentum" bot-pw quant 150000
    echo "momentum:$symbol:${lower}_momentum:bot-pw@$(provider_addr prime-co)" >>"$bots"
    broker_admin prime-co create-account "${lower}_meanrev" bot-pw prop 150000
    echo "meanrev:$symbol:${lower}_meanrev:bot-pw@$(provider_addr prime-co)" >>"$bots"

    for n in 1 2 3; do
      broker_admin retail-co create-account "${lower}_noise$n" bot-pw retail 40000
      subscribe_ipo retail-co "${lower}_noise$n" "$symbol" "$price" $(( shares / 100 ))
      echo "noise:$symbol:${lower}_noise$n:bot-pw@$(provider_addr retail-co)" >>"$bots"
    done
  done
  echo "seeded $(grep -vc '^#' "$bots") bots into $bots"
}

case "${1:-}" in
  members) seed_members ;;
  clearing) seed_clearing ;;
  venues) seed_venues ;;
  market) seed_market ;;
  *) echo "usage: scripts/seed.sh members|clearing|venues|market" >&2; exit 2 ;;
esac
